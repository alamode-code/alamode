TEMPERATURE_TAG = "  TMIN = 0\n  TMAX = 300\n  DT = 100\n"

# Files regenerated by every run (loaded state or full loop) and files that
# only the structural-optimization loop writes.
FILES_POSTPROCESS = ["qha_thermo", "V0"]
FILES_RELAX_LOOP = ["atom_disp", "umn_tensor", "normal_disp"]
STAGE_NAMES = (
    "fresh",
    "restart-h5",
    "text-io",
    "ialgo-mpi",
    "perturbative",
    "cell-override",
    "strainfile",
    "strainfile-cell2",
)


def isclose(a, b, rel_tol=1e-9, abs_tol=1.0e-12):
    return abs(a - b) <= max(rel_tol * max(abs(a), abs(b)), abs_tol)


def compare_files(file_now, file_ref, rel_tol, abs_tol, label):
    data_ref = np.loadtxt(file_ref, ndmin=2)
    data_now = np.loadtxt(file_now, ndmin=2)

    if data_ref.shape != data_now.shape:
        print(
            "%s: shape mismatch in %s: ref %s vs now %s"
            % (label, file_now, data_ref.shape, data_now.shape)
        )
        return 1

    ok = True
    for i in range(data_ref.shape[0]):
        for j in range(data_ref.shape[1]):
            ok = ok & isclose(data_ref[i, j], data_now[i, j], rel_tol, abs_tol)
    if not ok:
        diff = np.abs(data_now - data_ref)
        idx = np.unravel_index(np.argmax(diff), diff.shape)
        print(
            "%s: mismatch in %s at %s: ref %.16e now %.16e"
            % (label, file_now, str(idx), data_ref[idx], data_now[idx])
        )
        return 1
    return 0


def rewrite_input(
    template, fname, prefix, extra_general="", extra_qha="", relax_str=None
):
    with open(template) as f:
        text = f.read()

    for pattern in [
        "PREFIX = ZnO_qha",
        "  TMIN = 0\n  TMAX = 1000\n  DT = 100\n",
        "MODE = QHA\n",
        "RESTART_QHA = 0",
        "RELAX_STR = 2",
    ]:
        if pattern not in text:
            raise RuntimeError(
                "Template %s no longer contains %r" % (template, pattern)
            )

    text = text.replace("PREFIX = ZnO_qha", "PREFIX = %s" % prefix)
    text = text.replace("  TMIN = 0\n  TMAX = 1000\n  DT = 100\n", TEMPERATURE_TAG)
    if extra_general:
        text = text.replace("MODE = QHA\n", "MODE = QHA\n  %s\n" % extra_general)
    if extra_qha:
        text = text.replace("RESTART_QHA = 0", "RESTART_QHA = 0\n  %s" % extra_qha)
    if relax_str is not None:
        text = text.replace("RELAX_STR = 2", "RELAX_STR = %d" % relax_str)

    with open(fname, "w") as f:
        f.write(text)


def run_anphon(anphonbin, input_file, logfile, nprocs=1, timeout=1800):
    cmd = [anphonbin, input_file]
    if nprocs > 1:
        cmd = ["mpirun", "-np", str(nprocs)] + cmd
    try:
        with open(logfile, "w") as f:
            proc = subprocess.run(cmd, stdout=f, timeout=timeout)
    except subprocess.TimeoutExpired:
        print("Timeout while running %s (suspected MPI hang)" % input_file)
        return 1
    except Exception as e:
        print("Failed to launch %s: %s" % (cmd, e))
        return 1
    if proc.returncode != 0:
        print("anphon exited with code %d for %s" % (proc.returncode, input_file))
        return 1
    return 0


def snapshot(prefix, files, dest):
    os.makedirs(dest, exist_ok=True)
    for suffix in files:
        shutil.copy("%s.%s" % (prefix, suffix), dest)


def stage_fresh(anphonbin, refdir):
    rewrite_input("ZnO_qha_thermo.in", "qha_fresh.in", "ZnO_qha4")
    if run_anphon(anphonbin, "qha_fresh.in", "qha_fresh.log"):
        return 1
    snapshot("ZnO_qha4", FILES_POSTPROCESS + FILES_RELAX_LOOP, "fresh_out")

    # The committed references were generated on a different platform, so the
    # absolute floor must sit above cross-compiler noise on numerically zero
    # entries (symmetry-forbidden displacement components are O(1e-11)).
    info = 0
    for suffix in FILES_POSTPROCESS + FILES_RELAX_LOOP:
        info += compare_files(
            "ZnO_qha4.%s" % suffix,
            os.path.join(refdir, "ZnO_qha4.%s" % suffix),
            rel_tol=1.0e-8,
            abs_tol=1.0e-8,
            label="fresh",
        )
    # Iterative branch: recorded through the shared structural-optimization
    # loop, like SCPH.
    info += check_structure_group("ZnO_qha4", "ZnO_qha4.qha.h5")
    return info


def stage_restart_h5(anphonbin):
    rewrite_input("ZnO_qha_thermo.in", "qha_restart.in", "ZnO_qha4")
    with open("qha_restart.in") as f:
        text = f.read()
    with open("qha_restart.in", "w") as f:
        f.write(text.replace("RESTART_QHA = 0", "RESTART_QHA = 1"))

    if run_anphon(anphonbin, "qha_restart.in", "qha_restart.log"):
        return 1

    # The restart loads the state from ZnO_qha4.qha.h5 and regenerates the
    # postprocess outputs; they must match the fresh run exactly.
    info = 0
    for suffix in FILES_POSTPROCESS:
        info += compare_files(
            "ZnO_qha4.%s" % suffix,
            os.path.join("fresh_out", "ZnO_qha4.%s" % suffix),
            rel_tol=1.0e-12,
            abs_tol=1.0e-14,
            label="restart-h5",
        )
    return info


