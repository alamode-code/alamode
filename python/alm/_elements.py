def element_symbol(atomic_number):
    """Return the element symbol for ``atomic_number`` (``"E<Z>"`` if out of range)."""
    z = int(atomic_number)
    if 1 <= z < len(ELEMENT_SYMBOLS):
        return ELEMENT_SYMBOLS[z]
    return f"E{z}"
